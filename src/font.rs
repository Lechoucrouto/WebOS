const fn g(r0: u8, r1: u8, r2: u8, r3: u8, r4: u8, r5: u8, r6: u8) -> u64 {
    (r0 as u64)
        | ((r1 as u64) << 5)
        | ((r2 as u64) << 10)
        | ((r3 as u64) << 15)
        | ((r4 as u64) << 20)
        | ((r5 as u64) << 25)
        | ((r6 as u64) << 30)
}

pub fn glyph_for(ch: char) -> u64 {
    let code = ch as usize;
    if (32..=126).contains(&code) {
        FONT_5X7[code - 32]
    } else {
        FONT_5X7[31] // '?'
    }
}

